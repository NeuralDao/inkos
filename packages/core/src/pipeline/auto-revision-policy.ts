import type { Observation } from "../models/observation.js";
import type { ReviseMode } from "../agents/reviser.js";

export function usageFromError(error: unknown): { promptTokens: number; completionTokens: number; totalTokens: number } | undefined {
  const value = (error as { tokenUsage?: { promptTokens?: unknown; completionTokens?: unknown; totalTokens?: unknown } } | null)?.tokenUsage;
  if (!value || ![value.promptTokens, value.completionTokens, value.totalTokens].every((item) => typeof item === "number" && Number.isInteger(item) && item >= 0)) return undefined;
  return { promptTokens: value.promptTokens as number, completionTokens: value.completionTokens as number, totalTokens: value.totalTokens as number };
}

/** IDs are bound to the original review, not generated by a model. */
export interface RevisionFinding {
  readonly id: string;
  readonly observation: Observation;
}

export interface FindingAssessment {
  readonly findingId: string;
  readonly status: "resolved" | "remaining";
}

/** Retain neutral editorial observations as context alongside actionable issues. */
export function reviewFindings(observations: ReadonlyArray<Observation>): RevisionFinding[] {
  return observations.flatMap((observation, index) =>
    observation.category !== "execution" && observation.assessment !== "unavailable"
      ? [{ id: `finding-${index + 1}`, observation }]
      : [],
  );
}

export function actionableFindings(observations: ReadonlyArray<Observation>): RevisionFinding[] {
  return observations.flatMap((observation, index) =>
    observation.assessment === "issue" && observation.category !== "execution"
      ? [{ id: `finding-${index + 1}`, observation }]
      : [],
  );
}

export function revisionModeFor(findings: ReadonlyArray<RevisionFinding>): ReviseMode {
  const scopes = findings.map(({ observation }) => observation.scope?.trim().toLowerCase());
  if (scopes.includes("structural")) return "rework";
  if (scopes.length > 0 && scopes.every((scope) => scope === "local")) return "spot-fix";
  return "rewrite";
}
